import {createGenericBoundedInput,type GenericBoundedInput,type GenericInputSpec,type GenericInputStats} from './generic-bounded-input';
/** Bounded fast-wrapper/LZ4 patch decoding from Blob or random-access sources. */
export const STREAM_PATCH_SOURCE_LIMITS=Object.freeze({targetBytes:64*1024*1024,inputChunkBytes:32*1024,
  historyBytes:64*1024,matchScratchBytes:16*1024,patchBytes:16*1024,yieldAfterBytes:256*1024});
const STREAM_PATCH_LIMITS=STREAM_PATCH_SOURCE_LIMITS;
const ACTIVE_TARGETS=new WeakSet<ArrayBuffer>();

export interface SourceStreamPatchOptions {
  readonly xor?:boolean;
  readonly signal?:AbortSignal;
  readonly chunkBytes?:number;
  readonly yieldAfterBytes?:number;
  readonly yieldTask?:()=>Promise<void>;
}
export interface SourceStreamPatchStats {
  readonly encodedBytes:number;readonly decodedBytes:number;readonly patches:number;
  readonly inputReads:number;readonly peakInputBackingBytes:number;
  readonly targetBackingBytes:number;readonly historyBytes:number;readonly matchScratchBytes:number;
  readonly fixedHeaderBytes:number;readonly peakExplicitOwnedBytes:number;
  readonly yields:number;readonly codec:'raw'|'lz4';
  readonly scope:'explicit-decoder-buffers-only';
  readonly input:GenericInputStats;
  readonly timing:{readonly inputSetupMs:number;readonly inputReadAwaitMs:number;readonly yieldAwaitMs:number;readonly decodeActiveMs:number};
}

const BLOCK=STREAM_PATCH_LIMITS.patchBytes;
const fail=(detail:string):never=>{throw Error(`Invalid streaming patch: ${detail}`);};
const natural=(value:unknown,minimum=0):value is number=>Number.isSafeInteger(value)&&(value as number)>=minimum;
function waitWithAbort(promise:Promise<void>,signal?:AbortSignal):Promise<void> {
  if(!signal)return promise;
  return new Promise<void>((resolve,reject)=>{
    let settled=false;
    const clean=()=>signal.removeEventListener('abort',abort);
    const abort=()=>{if(settled)return;settled=true;clean();reject(signal.reason??new DOMException('Aborted','AbortError'));};
    signal.addEventListener('abort',abort,{once:true});
    promise.then(()=>{if(settled)return;settled=true;clean();resolve();},error=>{if(settled)return;settled=true;clean();reject(error);});
    if(signal.aborted)abort();
  });
}

/** Carries only 8 header bytes. Pixel spans are applied directly to the private
 * target; this object never retains an input span or an entire 16KiB patch. */
class PatchSink {
  readonly target:Uint8Array<ArrayBuffer>;
  readonly xor:boolean;
  readonly scratch=new Uint8Array(8);
  private stage:'count'|'header'|'data'|'done'='count';
  private headerUsed=0;
  private count=0;
  private patches=0;
  private from=0;
  private length=0;
  private dataUsed=0;
  private priorEnd=0;
  private bytes=0;

  constructor(target:Uint8Array<ArrayBuffer>,xor:boolean){this.target=target;this.xor=xor;}
  get parsedPatches(){return this.patches;}
  consume(input:Uint8Array):void {
    let at=0;
    while(at<input.byteLength){
      if(this.stage==='done')fail('trailing packed bytes');
      if(this.stage==='count'||this.stage==='header'){
        const required=this.stage==='count'?4:8,take=Math.min(required-this.headerUsed,input.length-at);
        this.scratch.set(input.subarray(at,at+take),this.headerUsed);this.headerUsed+=take;this.bytes+=take;at+=take;
        if(this.headerUsed!==required)continue;
        const view=new DataView(this.scratch.buffer);
        this.headerUsed=0;
        if(this.stage==='count'){
          this.count=view.getUint32(0,true);
          if(this.count>Math.ceil(this.target.length/BLOCK))fail('patch count');
          this.stage=this.count?'header':'done';
        }else{
          this.from=view.getUint32(0,true);this.length=view.getUint32(4,true);
          if(this.from<this.priorEnd||this.from%BLOCK||this.length!==Math.min(BLOCK,this.target.length-this.from)||
            this.length<=0||this.from+this.length>this.target.length)fail('patch bounds/order');
          this.dataUsed=0;this.stage='data';
        }
      }else{
        const take=Math.min(this.length-this.dataUsed,input.length-at),where=this.from+this.dataUsed;
        if(this.xor){for(let i=0;i<take;i++)this.target[where+i]^=input[at+i];}
        else this.target.set(input.subarray(at,at+take),where);
        this.dataUsed+=take;this.bytes+=take;at+=take;
        if(this.dataUsed===this.length){
          this.priorEnd=this.from+this.length;this.patches++;
          this.stage=this.patches===this.count?'done':'header';
        }
      }
    }
  }
  finish(expected:number):void {
    if(this.stage!=='done'||this.bytes!==expected||this.patches!==this.count)fail('truncated packed patch');
  }
}

/** LZ4 block decoder with a 64KiB rolling output history. Overlapping matches
 * read history after each generated byte, exactly like the reference decoder.
 * pump() stops at a work quantum even if a tiny match expands to megabytes. */
class Lz4Sink {
  readonly history=new Uint8Array(STREAM_PATCH_LIMITS.historyBytes);
  readonly scratch=new Uint8Array(STREAM_PATCH_LIMITS.matchScratchBytes);
  private readonly sink:PatchSink;
  private readonly expected:number;
  private stage:'token'|'literal-length'|'literal'|'offset-low'|'offset-high'|'match-length'|'match'='token';
  private token=0;
  private literalLength=0;
  private matchLength=0;
  private distance=0;
  private output=0;
  constructor(sink:PatchSink,expected:number){this.sink=sink;this.expected=expected;}
  get written(){return this.output;}
  get pendingOutput(){return this.stage==='match';}
  private literal(input:Uint8Array):void {
    if(this.output+input.length>this.expected)fail('literal output overflow');
    const first=Math.min(input.length,this.history.length-(this.output&65535));
    this.history.set(input.subarray(0,first),this.output&65535);
    if(first<input.length)this.history.set(input.subarray(first),0);
    this.output+=input.length;this.sink.consume(input);
  }
  pump(input:Uint8Array,begin:number,quota:number):{at:number;work:number} {
    let at=begin,work=0;
    while(work<quota){
      if(this.stage==='match'){
        const take=Math.min(this.matchLength,this.scratch.length,Math.max(1,quota-work));
        if(this.output+take>this.expected)fail('match output overflow');
        for(let i=0;i<take;i++){
          const value=this.history[(this.output-this.distance)&65535];
          this.scratch[i]=value;this.history[this.output&65535]=value;this.output++;
        }
        this.sink.consume(this.scratch.subarray(0,take));work+=take;this.matchLength-=take;
        if(this.matchLength===0)this.stage='token';
        continue;
      }
      if(at===input.length)break;
      if(this.stage==='literal'){
        const take=Math.min(this.literalLength,input.length-at,Math.max(1,Math.floor((quota-work)/2)));
        this.literal(input.subarray(at,at+take));at+=take;work+=take*2;this.literalLength-=take;
        if(!this.literalLength)this.stage='offset-low';
        continue;
      }
      const byte=input[at++];work++;
      if(this.stage==='token'){
        this.token=byte;this.literalLength=byte>>>4;
        if(this.literalLength===15)this.stage='literal-length';
        else{
          if(this.output+this.literalLength>this.expected)fail('literal output overflow');
          this.stage=this.literalLength?'literal':'offset-low';
        }
      }else if(this.stage==='literal-length'){
        this.literalLength+=byte;
        if(this.literalLength>this.expected||this.output+this.literalLength>this.expected)fail('literal length overflow');
        if(byte!==255)this.stage=this.literalLength?'literal':'offset-low';
      }else if(this.stage==='offset-low'){
        this.distance=byte;this.stage='offset-high';
      }else if(this.stage==='offset-high'){
        this.distance|=byte<<8;
        if(!this.distance||this.distance>this.output)fail('back-reference distance');
        this.matchLength=(this.token&15)+4;
        if((this.token&15)===15)this.stage='match-length';
        else{
          if(this.output+this.matchLength>this.expected)fail('match output overflow');
          this.stage='match';
        }
      }else if(this.stage==='match-length'){
        this.matchLength+=byte;
        if(this.matchLength>this.expected||this.output+this.matchLength>this.expected)fail('match length overflow');
        if(byte!==255)this.stage='match';
      }else fail('decoder state');
    }
    return {at,work};
  }
  finish():void {
    // The reference accepts an end directly after a match or the literals of a
    // final sequence. No pending extension, offset byte or payload is allowed.
    if(this.output!==this.expected||!['token','offset-low'].includes(this.stage))fail('truncated LZ4 block');
  }
}

/** Consumes OWNERSHIP of target's private full backing buffer. Never expose it
 * before success. Any failure/abort leaves an invalid partial target which the
 * caller must discard. Frame policy and pixel-hash validation remain caller
 * responsibilities; this function does not measure process/GPU/native memory. */
export async function decodeFastPixelPatchFromSource(spec:GenericInputSpec,ownedTarget:Uint8Array<ArrayBuffer>,options:SourceStreamPatchOptions={}):Promise<{
  pixels:Uint8Array<ArrayBuffer>;stats:SourceStreamPatchStats;
}> {
  const {signal}=options;signal?.throwIfAborted();
  const chunkBytes=options.chunkBytes??STREAM_PATCH_LIMITS.inputChunkBytes,
    yieldAfterBytes=options.yieldAfterBytes??STREAM_PATCH_LIMITS.yieldAfterBytes;
  if(!(ownedTarget instanceof Uint8Array)||!(ownedTarget.buffer instanceof ArrayBuffer)||ownedTarget.byteOffset!==0||
    ownedTarget.byteLength!==ownedTarget.buffer.byteLength||(ownedTarget.buffer as ArrayBuffer&{resizable?:boolean}).resizable||
    ownedTarget.byteLength>STREAM_PATCH_LIMITS.targetBytes)fail('owned target backing');
  const targetBacking=ownedTarget.buffer,targetBytes=ownedTarget.byteLength;
  const requireOwnership=()=>{
    if(ownedTarget.buffer!==targetBacking||ownedTarget.byteOffset!==0||ownedTarget.byteLength!==targetBytes||targetBacking.byteLength!==targetBytes)
      fail('owned target changed during await');
    // A detached empty buffer also has length0; a zero-length view distinguishes
    // it without allocating a replacement backing store.
    if(targetBytes===0)try{new DataView(targetBacking,0,0);}catch{fail('owned target detached');}
  };
  requireOwnership();
  if(!natural(chunkBytes,1)||chunkBytes>STREAM_PATCH_LIMITS.inputChunkBytes||!natural(yieldAfterBytes,1)||yieldAfterBytes>1024*1024||
    options.xor!==undefined&&typeof options.xor!=='boolean'||options.yieldTask!==undefined&&typeof options.yieldTask!=='function')fail('options');
  if(ACTIVE_TARGETS.has(targetBacking))fail('target already has an active decoder');
  ACTIVE_TARGETS.add(targetBacking);
  try{
  const maximum=ownedTarget.length+Math.ceil(ownedTarget.length/BLOCK)*8+4;
  const wrapper=new Uint8Array(5),sink=new PatchSink(ownedTarget,options.xor===true);
  let wrapperUsed=0,expected=-1,mode=-1,lz4:Lz4Sink|undefined,decoded=0,inputReads=0,peakInputBackingBytes=0;
  let yields=0,work=0,yieldAwaitMs=0,decodeActiveMs=0,peakExplicitOwnedBytes=ownedTarget.buffer.byteLength+wrapper.byteLength+sink.scratch.byteLength;
  let inputSource:GenericBoundedInput|undefined;
  const yieldTask=options.yieldTask??(()=>new Promise<void>(resolve=>setTimeout(resolve,0)));
  const cooperate=async()=>{
    signal?.throwIfAborted();requireOwnership();inputSource?.assertUnchanged();const waiting=performance.now();
    try{await waitWithAbort(Promise.resolve().then(yieldTask),signal);}finally{yieldAwaitMs+=performance.now()-waiting;}
    yields++;signal?.throwIfAborted();requireOwnership();inputSource?.assertUnchanged();work=0;
  };
  const setupStarted=performance.now();
  inputSource=await createGenericBoundedInput(spec,{chunkBytes,signal});
  const inputSetupMs=performance.now()-setupStarted;
  let input:Uint8Array<ArrayBuffer>|undefined;
  try{
  requireOwnership();
  if(!natural(inputSource.size,5)||inputSource.size>STREAM_PATCH_LIMITS.targetBytes+64_000)fail('encoded input size');
  while(true){
    signal?.throwIfAborted();input=undefined;
    const chunk=await inputSource.next();
    signal?.throwIfAborted();requireOwnership();
    if(!chunk)break;
    if(!(chunk instanceof Uint8Array)||!(chunk.buffer instanceof ArrayBuffer)||(chunk.buffer as ArrayBuffer&{resizable?:boolean}).resizable||
      chunk.buffer===targetBacking||chunk.byteOffset!==0||chunk.byteLength<1||chunk.byteLength>chunkBytes||
      chunk.buffer.byteLength>chunkBytes)fail('generic input backing');
    input=chunk;inputReads++;peakInputBackingBytes=Math.max(peakInputBackingBytes,input.buffer.byteLength);
    let at=0;
    let activeStarted=performance.now();
    while(at<input.length||lz4?.pendingOutput){
      signal?.throwIfAborted();
      if(wrapperUsed<5){
        const take=Math.min(5-wrapperUsed,input.length-at);
        wrapper.set(input.subarray(at,at+take),wrapperUsed);wrapperUsed+=take;at+=take;work+=take;
        if(wrapperUsed<5)continue;
        mode=wrapper[0];expected=new DataView(wrapper.buffer).getUint32(1,true);
        if(mode>1||expected>maximum||expected<4)fail('wrapper kind/output size');
        if(mode===0&&inputSource.size!==5+expected)fail('raw wrapper length');
        if(mode===1)lz4=new Lz4Sink(sink,expected);
      }
      peakExplicitOwnedBytes=Math.max(peakExplicitOwnedBytes,ownedTarget.buffer.byteLength+wrapper.byteLength+sink.scratch.byteLength+
        input.buffer.byteLength+(lz4?lz4.history.byteLength+lz4.scratch.byteLength:0));
      if(work>=yieldAfterBytes){decodeActiveMs+=performance.now()-activeStarted;await cooperate();activeStarted=performance.now();continue;}
      if(mode===0){
        const take=Math.min(input.length-at,Math.max(1,Math.floor((yieldAfterBytes-work)/2)));
        if(decoded+take>expected)fail('raw output overflow');
        sink.consume(input.subarray(at,at+take));at+=take;decoded+=take;work+=take*2;
      }else{
        const processed=lz4!.pump(input,at,yieldAfterBytes-work);
        if(processed.at===at&&processed.work===0)break;
        at=processed.at;work+=processed.work;decoded=lz4!.written;
      }
    }
    decodeActiveMs+=performance.now()-activeStarted;
  }
  }finally{input=undefined;await inputSource.dispose();}
  input=undefined;signal?.throwIfAborted();requireOwnership();
  inputSource.assertUnchanged();
  if(inputSource.stats.bytes!==inputSource.size||!inputSource.stats.eof||inputSource.stats.readPending)fail('generic input not exactly consumed');
  if(wrapperUsed!==5)fail('truncated wrapper');
  lz4?.finish();sink.finish(expected);
  if(decoded!==expected)fail('decoded size');
  return {pixels:ownedTarget,stats:Object.freeze({encodedBytes:inputSource.size,decodedBytes:decoded,patches:sink.parsedPatches,
    inputReads,peakInputBackingBytes,targetBackingBytes:ownedTarget.buffer.byteLength,
    historyBytes:lz4?.history.byteLength??0,matchScratchBytes:lz4?.scratch.byteLength??0,
    fixedHeaderBytes:wrapper.byteLength+sink.scratch.byteLength,peakExplicitOwnedBytes,yields,
    codec:mode===0?'raw':'lz4',scope:'explicit-decoder-buffers-only',input:inputSource.stats,
    timing:Object.freeze({inputSetupMs,inputReadAwaitMs:inputSource.stats.readAwaitMs,yieldAwaitMs,decodeActiveMs})})};
  }finally{ACTIVE_TARGETS.delete(targetBacking);}
}
